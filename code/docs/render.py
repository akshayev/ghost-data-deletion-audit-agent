"""Fill {{key}} placeholders in *.md.tmpl files from code/evaluation/runs/numbers.json.

    python code/docs/render.py            # README.md, ARCHITECTURE.md, DECISIONS.md, ...

Keys are dotted paths into numbers.json ({{sample.det.step_f1}}). A key that is missing, or
that points at a list/object, is an error: nothing is written and the unresolved keys are
listed, so a rendered document can never contain a stray placeholder or a hand-typed number.
"""

import json
import re
import sys
from pathlib import Path

CODE_DIR = Path(__file__).resolve().parents[1]
if str(CODE_DIR) not in sys.path:
    sys.path.insert(0, str(CODE_DIR))

from ghost import paths  # noqa: E402

NUMBERS = paths.EVAL_RUNS / "numbers.json"
PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.\-]+)\s*\}\}")
SKIP_DIRS = {".venv", ".git", "dataset", "__pycache__", "node_modules", "runs"}
HEADER = "<!-- Generated by code/docs/render.py from {src}; edit the template, not this file. -->\n"


class MissingKey(KeyError):
    """Unresolved placeholders (the message lists them all)."""


def lookup(numbers: dict, key: str):
    value = numbers
    for part in key.split("."):
        if not isinstance(value, dict) or part not in value:
            raise KeyError(key)
        value = value[part]
    if isinstance(value, dict | list):
        raise KeyError(key)
    return value


def render_text(text: str, numbers: dict) -> str:
    missing: list[str] = []

    def sub(match: re.Match) -> str:
        try:
            return str(lookup(numbers, match.group(1)))
        except KeyError:
            missing.append(match.group(1))
            return match.group(0)

    out = PLACEHOLDER.sub(sub, text)
    if missing:
        raise MissingKey("unresolved placeholders: " + ", ".join(sorted(set(missing))))
    return out


def templates(root: Path) -> list[Path]:
    return sorted(p for p in root.rglob("*.md.tmpl")
                  if not (set(p.relative_to(root).parts) & SKIP_DIRS))


def render_all(root: Path = paths.REPO_ROOT, numbers_path: Path = NUMBERS) -> list[Path]:
    numbers = json.loads(numbers_path.read_text(encoding="utf-8"))
    rendered = {t: render_text(t.read_text(encoding="utf-8"), numbers) for t in templates(root)}
    written = []
    for tmpl, text in rendered.items():  # all-or-nothing: nothing is written on an error
        target = tmpl.with_suffix("")
        target.write_text(HEADER.format(src=tmpl.name) + text, encoding="utf-8", newline="\n")
        written.append(target)
    return written


def main() -> int:
    if not NUMBERS.exists():
        print(f"{NUMBERS} not found: run python code/evaluation/report_numbers.py first",
              file=sys.stderr)
        return 1
    try:
        written = render_all()
    except MissingKey as exc:
        print(exc, file=sys.stderr)
        return 1
    for path in written:
        print(f"rendered {path.relative_to(paths.REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
